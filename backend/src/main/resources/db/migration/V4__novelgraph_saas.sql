-- SaaS独立数据结构；不删除原小说或生成记录。全部表字段附中文注释。

CREATE TABLE saas_user (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '主键',
  email VARCHAR(200) NOT NULL COMMENT '登录邮箱',
  name VARCHAR(100) NOT NULL COMMENT '显示名称',
  password_hash VARCHAR(400) NOT NULL COMMENT '加盐密码散列',
  verified INT NOT NULL DEFAULT 0 COMMENT '邮箱验证状态',
  platform_role VARCHAR(30) NOT NULL DEFAULT 'USER' COMMENT '平台角色',
  status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE' COMMENT '账号状态',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
  UNIQUE KEY uk_user_email(email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='SaaS用户账号';

CREATE TABLE saas_session (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '主键',
  user_id BIGINT NOT NULL COMMENT '账号',
  token_hash VARCHAR(64) NOT NULL COMMENT '会话令牌散列',
  csrf VARCHAR(100) NOT NULL COMMENT '跨站请求校验值',
  expires_at DATETIME(3) NOT NULL COMMENT '失效时间',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
  UNIQUE KEY uk_session_token(token_hash), CONSTRAINT fk_session_user FOREIGN KEY(user_id) REFERENCES saas_user(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='可吊销用户会话';

CREATE TABLE saas_tenant (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '主键',
